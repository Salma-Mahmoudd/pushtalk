import asyncio
import shutil
import uuid
from pathlib import Path


class FileStorage:
    """Media files under one root folder, addressed by keys such as "processed/<id>.ogg".

    Keys are generated by the server; a key that would leave the root is refused anyway.
    """

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError(f"key outside the media root: {key!r}")
        return path

    def temp_path(self, suffix: str = "") -> Path:
        """A fresh path on the same disk, so moving it into place is atomic."""
        folder = self.root / "tmp"
        folder.mkdir(parents=True, exist_ok=True)
        return folder / f"{uuid.uuid4().hex}{suffix}"

    async def move_in(self, source: Path, key: str) -> None:
        target = self.path(key)
        await asyncio.to_thread(target.parent.mkdir, parents=True, exist_ok=True)
        await asyncio.to_thread(shutil.move, source, target)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self.path(key).unlink, missing_ok=True)

    def exists(self, key: str) -> bool:
        return self.path(key).is_file()
